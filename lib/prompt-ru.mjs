// Русские таблицы текстов хоста dsh-soul (слой A: «механика языка»).
//
// Контракт: набор ключей 1:1 с `PROMPT_TEXT.en` / `COMMAND_MESSAGES.en` вендорского
// index.mjs. Единственное намеренное отличие — `replyLanguage.ru` (сама строка, которая
// задаёт язык ответа); ключи `replyLanguage.zh` / `.en` сохранены ради совпадения набора
// ключей и в этой таблице недостижимы: `buildBehavior()` берёт `replyLanguage[config.language]`,
// а таблица RU выбирается только при `language === 'ru'`.
//
// Тон: живой русский без канцелярита, термины как в ядре DSH — сессия, рабочая область,
// пресет, навык. Плейсхолдеры `${n}` / `${o}` / `${b}` / `${name}` и арность функций
// повторяют en-версию: интеграция (`promptTextOf` / `commandMessages`) подставляет их
// ровно так же.
//
// Вендорский index.mjs этот файл не импортирует — подключение делает слой A
// (`promptTextOf`/`commandMessages`), вендорские литералы PROMPT_TEXT / COMMAND_MESSAGES
// остаются нетронутыми (иначе вендорская проверка «ровно 2 блока tables/replyLength»
// в scripts/verify-config.mjs покраснеет).

// Русское склонение числительных: 1 поле / 2 поля / 5 полей.
// Живёт вне таблиц: внутри объекта это был бы лишний ключ и сломало бы сверку 1:1 с en.
function ruPlural(n, one, few, many) {
  const mod10 = Math.abs(n) % 10
  const mod100 = Math.abs(n) % 100
  if (mod100 >= 11 && mod100 <= 14) return many
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}

